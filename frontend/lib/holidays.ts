export const ALL_HOLIDAYS: HolidayItem[] = [...INDIA_HOLIDAYS, ...WORLD_HOLIDAYS].sort(
  (a, b) => new Date(a.startDate).getTime() - new Date(b.startDate).getTime()
);

export function getUpcomingHolidays(filterRegion?: 'India' | 'World', limit = 6): HolidayItem[] {
  const now = new Date();
  const list = filterRegion === 'India' 
    ? INDIA_HOLIDAYS 
    : filterRegion === 'World' 
      ? WORLD_HOLIDAYS 
      : ALL_HOLIDAYS;

  return list
    .filter((h) => new Date(h.endDate) >= now)
    .slice(0, limit);
}

