  static List<HolidayModel> getAllHolidays() {
    final all = [...indiaHolidays, ...worldHolidays];
    all.sort((a, b) => a.start.compareTo(b.start));
    return all;
  }

  static HolidayModel? getNextUpcomingHoliday({String? regionPreference}) {
    final now = DateTime.now();
    List<HolidayModel> list;
    if (regionPreference == 'India') {
      list = indiaHolidays;
    } else if (regionPreference == 'World') {
      list = worldHolidays;
    } else {
      list = getAllHolidays();
    }

    for (final h in list) {
      if (h.end.isAfter(now)) {
        return h;
      }
    }
    return null;
  }
