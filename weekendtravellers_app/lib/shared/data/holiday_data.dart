/// Curated Holiday and Long Weekend Calendar for India and the World
class HolidayModel {
  final String id;
  final String title;
  final String region; // 'India' or 'World'
  final String country;
  final String flag;
  final DateTime start;
  final DateTime end;
  final int days;
  final String tag;
  final String description;
  final List<String> recommendedDestinations;
  final String searchQuery;

  const HolidayModel({
    required this.id,
    required this.title,
    required this.region,
    required this.country,
    required this.flag,
    required this.start,
    required this.end,
    required this.days,
    required this.tag,
    required this.description,
    required this.recommendedDestinations,
    required this.searchQuery,
  });

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'title': title,
      'region': region,
      'country': country,
      'flag': flag,
      'start': start,
      'end': end,
      'days': days,
      'tag': tag,
      'description': description,
      'recommendedDestinations': recommendedDestinations,
      'searchQuery': searchQuery,
    };
  }
}

