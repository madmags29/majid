  static DestinationModel? getBySlug(String slug) {
    try {
      final s = slug.toLowerCase().trim();
      return destinations.firstWhere((d) =>
          d.slug.toLowerCase() == s ||
          d.name.toLowerCase() == s ||
          d.id.toLowerCase() == s ||
          d.slug.toLowerCase().replaceAll('-', ' ') == s.replaceAll('-', ' '));
    } catch (_) {
      try {
        final s = slug.toLowerCase().trim();
        return destinations.firstWhere((d) =>
            d.name.toLowerCase().contains(s) || d.slug.toLowerCase().contains(s));
      } catch (_) {
        return destinations.first;
      }
    }
  }

  static List<DestinationModel> search(String query) {
    if (query.isEmpty) return destinations;
    final q = query.toLowerCase();
    return destinations.where((d) {
      return d.name.toLowerCase().contains(q) ||
          d.city.toLowerCase().contains(q) ||
          d.state.toLowerCase().contains(q) ||
          d.country.toLowerCase().contains(q) ||
          d.categories.any((c) => c.toLowerCase().contains(q)) ||
          d.famousFor.toLowerCase().contains(q);
    }).toList();
  }

  static List<DestinationModel> filterBy({
    String? category,
    int? maxBudget,
    int? maxDistanceKm,
    String? originCity,
    double? userLat,
    double? userLng,
  }) {
    final list = destinations.where((d) {
      if (category != null && category != 'All' && !category.contains('Nearby')) {
        final matchesCat = d.categories.any((c) => c.toLowerCase().contains(category.toLowerCase())) ||
            d.idealFor.any((i) => i.toLowerCase().contains(category.toLowerCase()));
        if (!matchesCat) return false;
      }
      if (maxBudget != null && d.minBudget > maxBudget) {
        return false;
      }
      if (maxDistanceKm != null) {
        final dist = d.getDistanceKm(originCity ?? 'Delhi', userLat, userLng);
        if (dist > maxDistanceKm) return false;
      }
      return true;
    }).toList();

    final origin = originCity ?? 'Delhi';
    list.sort((a, b) => a.getDistanceKm(origin, userLat, userLng).compareTo(b.getDistanceKm(origin, userLat, userLng)));

    return list;
  }
